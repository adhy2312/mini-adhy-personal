export class ElectronicsEngineeringNexus {
  /**
   * Derives resistor voltage divider values or output voltage
   */
  calculateVoltageDivider({ vin, r1, r2, vout }) {
    if (vin !== undefined && r1 !== undefined && r2 !== undefined) {
      const calculatedVout = vin * (r2 / (r1 + r2));
      const current = vin / (r1 + r2);
      const p1 = Math.pow(current, 2) * r1;
      const p2 = Math.pow(current, 2) * r2;
      return {
        vout: parseFloat(calculatedVout.toFixed(4)),
        currentAmps: parseFloat(current.toFixed(6)),
        dissipationR1_Watts: parseFloat(p1.toFixed(5)),
        dissipationR2_Watts: parseFloat(p2.toFixed(5)),
        formula: 'Vout = Vin * (R2 / (R1 + R2))'
      };
    }

    if (vin !== undefined && vout !== undefined && r2 !== undefined) {
      // Find R1: Vout = Vin * R2 / (R1 + R2) => R1 = R2 * (Vin - Vout) / Vout
      const calculatedR1 = r2 * (vin - vout) / vout;
      return {
        r1: parseFloat(calculatedR1.toFixed(2)),
        r2,
        vin,
        vout,
        formula: 'R1 = R2 * (Vin - Vout) / Vout'
      };
    }

    throw new Error('Provide either (vin, r1, r2) or (vin, vout, r2)');
  }

  /**
   * Computes RC low-pass and high-pass filter cutoff frequency and impedance
   */
  calculateRcFilter({ r, c, targetFrequency }) {
    if (r !== undefined && c !== undefined) {
      // fc = 1 / (2 * pi * R * C)
      const fc = 1 / (2 * Math.PI * r * c);
      const timeConstant = r * c;
      return {
        cutoffFrequencyHz: parseFloat(fc.toFixed(2)),
        timeConstantSeconds: parseFloat(timeConstant.toFixed(6)),
        resistanceOhms: r,
        capacitanceFarads: c,
        formula: 'fc = 1 / (2 * π * R * C)'
      };
    }

    if (targetFrequency !== undefined && c !== undefined) {
      // R = 1 / (2 * pi * fc * C)
      const calculatedR = 1 / (2 * Math.PI * targetFrequency * c);
      return {
        resistanceOhms: parseFloat(calculatedR.toFixed(2)),
        capacitanceFarads: c,
        targetFrequencyHz: targetFrequency,
        formula: 'R = 1 / (2 * π * fc * C)'
      };
    }

    throw new Error('Provide either (r, c) or (targetFrequency, c)');
  }

  /**
   * Op-Amp Closed-Loop Gain Calculations (Inverting and Non-Inverting)
   */
  calculateOpAmpGain({ type = 'non-inverting', rIn, rFeedback }) {
    if (!rIn || !rFeedback) throw new Error('rIn and rFeedback are required');

    if (type.toLowerCase() === 'non-inverting') {
      // Av = 1 + (Rf / Rin)
      const gain = 1 + (rFeedback / rIn);
      const gainDb = 20 * Math.log10(gain);
      return {
        configuration: 'Non-Inverting Amplifier',
        voltageGain: parseFloat(gain.toFixed(3)),
        gainDb: parseFloat(gainDb.toFixed(2)),
        formula: 'Av = 1 + (Rf / Rin)'
      };
    } else {
      // Av = - (Rf / Rin)
      const gain = -(rFeedback / rIn);
      const gainDb = 20 * Math.log10(Math.abs(gain));
      return {
        configuration: 'Inverting Amplifier',
        voltageGain: parseFloat(gain.toFixed(3)),
        gainDb: parseFloat(gainDb.toFixed(2)),
        formula: 'Av = - (Rf / Rin)'
      };
    }
  }

  /**
   * Thermal Dissipation & Heatsink Modeling
   */
  calculateThermalDissipation({ powerWatts, ambientTempC = 25, junctionMaxTempC = 125, thetaJunctionAmbient }) {
    if (!powerWatts || !thetaJunctionAmbient) {
      throw new Error('powerWatts and thetaJunctionAmbient are required');
    }
    const tempRise = powerWatts * thetaJunctionAmbient;
    const estimatedJunctionTemp = ambientTempC + tempRise;
    const isSafe = estimatedJunctionTemp < junctionMaxTempC;
    const margin = junctionMaxTempC - estimatedJunctionTemp;

    return {
      powerDissipatedWatts: powerWatts,
      ambientTempC,
      estimatedJunctionTempC: parseFloat(estimatedJunctionTemp.toFixed(1)),
      maxAllowedTempC: junctionMaxTempC,
      thermalMarginC: parseFloat(margin.toFixed(1)),
      isSafeThermalDesign: isSafe,
      verdict: isSafe ? 'THERMAL_DESIGN_COMPLIANT' : 'HEATSINK_REQUIRED_OVERHEAT_RISK',
      formula: 'Tjunction = Tambient + (Power * ThetaJA)'
    };
  }

  /**
   * Generates a valid SPICE simulation netlist (.cir)
   */
  generateSpiceNetlist(circuitName, components = []) {
    const lines = [
      `* SPICE Netlist generated by Mini-Adhy Engineering Intelligence`,
      `* Circuit: ${circuitName}`,
      `* Timestamp: ${new Date().toISOString()}`,
      ``
    ];

    for (const comp of components) {
      // e.g. R1 1 2 10k
      lines.push(`${comp.ref} ${comp.nodes.join(' ')} ${comp.value}`);
    }

    lines.push(``);
    lines.push(`.tran 0.1m 10m`);
    lines.push(`.control`);
    lines.push(`run`);
    lines.push(`plot v(out)`);
    lines.push(`.endc`);
    lines.push(`.end`);

    return {
      circuitName,
      netlistText: lines.join('\n'),
      totalComponents: components.length
    };
  }
}
